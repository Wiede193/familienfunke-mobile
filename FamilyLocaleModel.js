export function englishRouteMatches(query,routes){
 const text=String(query||'').toLowerCase().replace(/[^a-z0-9 ]/g,' ').trim();
 const terms=text.split(/ +/).filter(t=>t.length>2&&!['the','and','for','find','how','can','with','please','you','my','your','want','would','like','near'].includes(t));
 if(!terms.length)return [];
 const direct=[[/\b(notification settings|push)\b/,'push'],[/\b(private messages|chat)\b/,'chat'],[/\b(sell|list an item|give away)\b/,'sell'],[/\b(jeans|stroller|trousers|marketplace|buy)\b/,'market'],[/\b(playground|playgrounds)\b/,'map'],[/\b(calendar|appointments)\b/,'calendar'],[/\b(sudoku|solitaire|chess|quiz|quizzes|puzzles|games)\b/,'play']];
 for(const [pattern,id] of direct){if(pattern.test(text))return routes.filter(r=>r.id===id);}
 return routes.map(r=>({...r,score:terms.reduce((n,t)=>n+((ENGLISH_SEARCH[r.id]||'').split(' ').some(w=>w===t||w===t.replace(/s$/,''))?1:0),0)})).filter(r=>r.score>0).sort((a,b)=>b.score-a.score).slice(0,6);
}
