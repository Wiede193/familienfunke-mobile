export function normalizeLanguage(value){return LANGUAGE_OPTIONS.includes(value)?value:'auto';}
export function resolveLanguage(preference,deviceLocale){return preference==='de'||preference==='en'?preference:/^en(?:[-_]|$)/i.test(String(deviceLocale||''))?'en':'de';}
export function localeFor(language){return language==='en'?'en-GB':'de-DE';}
export function translate(language,key){return language==='en'?(Object.hasOwn(EN,key)?EN[key]:key):key;}
export function formatServiceMoney(cents,language){return new Intl.NumberFormat(localeFor(language),{style:'currency',currency:SERVICE_CURRENCY}).format(Number(cents||0)/100);}
