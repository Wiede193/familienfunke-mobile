import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const mod=await import('data:text/javascript;base64,'+Buffer.from(read('FamilyTopicsKnowledge.js')).toString('base64'));
const {FAMILY_TOPIC_CATEGORIES,FAMILY_TOPIC_ARTICLES,findFamilyTopics}=mod;
assert.equal(FAMILY_TOPIC_CATEGORIES.length,5);
assert.equal(FAMILY_TOPIC_ARTICLES.length,17);
assert.equal(new Set(FAMILY_TOPIC_ARTICLES.map(a=>a.id)).size,17);
for(const item of FAMILY_TOPIC_ARTICLES){
 assert.ok(item.title.length>15,item.id);
 assert.ok(item.overview.length>=120,item.id+' overview');
 assert.ok(item.steps.length>=4,item.id+' four next steps');
 assert.ok(item.responsible.length>=25,item.id+' responsibility');
 assert.ok(item.documents.length>=25,item.id+' documents');
 assert.ok(item.caveat.length>=55,item.id+' caveats');
 assert.ok(item.sources.length>=1,item.id+' source');
 assert.ok(item.sources.every(s=>s.url.startsWith('https://')&&s.title));
 assert.ok(FAMILY_TOPIC_CATEGORIES.some(cat=>cat.id===item.category),item.id+' category');
}
assert.ok(findFamilyTopics('KiZ').some(a=>a.id==='kinderzuschlag'),'Article contains the official KiZ-Lotse term');
assert.ok(findFamilyTopics('kinderzuschlag').some(a=>a.id==='kinderzuschlag'));
assert.ok(findFamilyTopics('wohngeld').some(a=>a.id==='wohngeld'));
for(const id of ['kinderkrankengeld','mutter-vater-kind-kur','ganztag-grundschule','familienerholung','beistandschaft','haushaltshilfe-eltern-krank'])assert.ok(FAMILY_TOPIC_ARTICLES.some(a=>a.id===id),id);
assert.ok(findFamilyTopics('FrÜhE hIlFeN').some(a=>a.id==='fruehe-hilfen'));
assert.ok(findFamilyTopics('Medien').some(a=>a.id==='medien-alltag'));
assert.deepEqual(findFamilyTopics('unbekannte-suchfolge'),[]);
assert.ok(findFamilyTopics('Kita','care').every(a=>a.category==='care'));
const ui=read('FamilyTopicsSection.jsx'),guide=read('FamilyGuide.jsx');
assert.match(ui,/findFamilyTopics\(query,category\)/);
assert.match(ui,/FAMILY_TOPIC_CATEGORIES\.map/);
assert.match(ui,/item\.steps\.map/);
assert.match(ui,/item\.sources\.map/);
assert.match(ui,/Suche und Auswahl werden nicht gespeichert/);
assert.doesNotMatch(ui,/supabase|AsyncStorage/);
assert.match(guide,/import FamilyTopicsSection from '\.\/FamilyTopicsSection'/);
assert.match(guide,/<FamilyTopicsSection\/>/);
const map=read('FamilyMapBrandenburg.js'),server=read('supabase/functions/ff-app-assistant/FamilyMapBrandenburg.js');
assert.equal(map,server,'Assistant and map must share identical approved destination allowlists');
assert.match(map,/bb-schwapp-fuerstenwalde/);
assert.match(map,/bb-mykidsland-frankfurt/);
assert.match(map,/bb-duellarena-scharmuetzelbob/);
assert.match(map,/bb-bistro-kobel-wildpark/);
assert.match(map,/bb-fitolino-eberswalde/);
assert.match(map,/bb-saarowtherme/);
assert.match(map,/bb-turm-erlebniscity-oranienburg/);
assert.match(map,/Freitags und samstags.*ab 16 Jahren/);
assert.match(map,/Die Kartenmarkierung liegt näherungsweise/);
console.log('Family topics, official sources, private search and curated family activity focus verified.');
