import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const code=p=>'data:text/javascript;base64,'+Buffer.from(p).toString('base64');
const model=code(read('FamilyLayoutModel.js'));
const {decodeLocalLayout,resolveLayout,encodeLocalLayout}=await import(code(read('FamilyLayoutSync.js').replace("'./FamilyLayoutModel'","'"+model+"'")));
const remote={home:['play'],bottom:['home','play'],revision:3};
assert.deepEqual(resolveLayout(decodeLocalLayout(null),remote,true).value.home,['play']);
const local=decodeLocalLayout({version:1,home:['map'],bottom:['home','map']});
const conflict=resolveLayout(local,remote,true);assert.equal(conflict.conflict,true);assert.deepEqual(conflict.value.home,['map']);
const pending=decodeLocalLayout(JSON.parse(encodeLocalLayout(local.value,true,3)));
assert.equal(resolveLayout(pending,remote,true).conflict,false);
assert.equal(resolveLayout(pending,null,false).pending,true);
assert.equal(resolveLayout(pending,null,true).conflict,true);
assert.equal(resolveLayout(decodeLocalLayout(JSON.parse(encodeLocalLayout({version:1,home:['play'],bottom:['home','play']},true,2))),remote,true).pending,false);
const sql=read('database/ff_layout_preferences.sql'),client=read('FamilyLayoutPreferences.js');
assert.match(sql,/enable row level security/);assert.match(sql,/from public,anon,authenticated/);
assert.match(sql,/using\(user_id=\(select auth.uid\(\)\)\) with check\(user_id=\(select auth.uid\(\)\)\)/);
assert.match(sql,/on delete cascade/);assert.match(sql,/bottom\[1\]='home'/);
assert.match(client,/eq\('user_id',userId\)\.eq\('revision',remoteRevision\)/);
assert.match(client,/owner.current!==userId/);assert.match(client,/current.conflict&&!confirmConflict/);
assert.doesNotMatch(sql,/security definer|grant .* to anon/i);
console.log('Layout sync: offline retention, conflict detection, RLS contracts and compare-and-swap checked');
