import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const load=p=>import('data:text/javascript;base64,'+Buffer.from(read(p)).toString('base64'));
const {translate,formatServiceMoney}=await load('FamilyLocaleModel.js');
const {displayCalendarDay,calendarFields,monthDays}=await load('CalendarDates.js');
const {planSteps,AGES,INTERESTS,DURATIONS}=await load('FamilyOutingPlan.js');
const t=k=>translate('en',k);
assert.equal(t('Alle Benachrichtigungen löschen?'),'Delete all notifications?');
assert.equal(t('Kalendereintrag löschen?'),'Delete calendar entry?');
assert.match(displayCalendarDay('2026-12-05','en-GB'),/05 Dec 2026/);
assert.match(displayCalendarDay('2026-12-05','de-DE'),/05\. Dez\.? 2026/);
assert.deepEqual(calendarFields({title:'Test',day:'2026-12-05',time:'08:30',note:''}),{title:'Test',day:'2026-12-05',local_time:'08:30',note:''});
assert.equal(monthDays('2026-11').findIndex(Boolean),6);
for(const [,label] of [...AGES,...INTERESTS,...DURATIONS])assert.notEqual(t(label),label,label);
const places=[{title:'Burg Storkow'},{title:'Wildpark Frankfurt'}];
assert.match(planSteps('weekend',places,['baby'],'en')[0],/Saturday: Burg Storkow/);
assert.match(planSteps('weekend',places,['baby'],'en')[1],/No combined route has been calculated/);
assert.match(planSteps('weekend',places,['baby'],'en')[2],/flexible/);
assert.match(planSteps('full',places,[],'de')[0],/Vormittag:/);
const screen=read('NotificationCenterScreen.jsx');
const eventCopy=new Function('formatServiceMoney',screen.slice(screen.indexOf('const copy='),screen.indexOf('const formatDate='))+';return eventCopy;')(formatServiceMoney);
const price=eventCopy({kind:'price',old_price_cents:500,new_price_cents:300},t,'en');
assert.equal(price[0],'Price reduced');
assert.match(price[1],/€5\.00 to €3\.00/);
assert.match(price[1],/current price/);
assert.equal(eventCopy({kind:'request'},t,'en')[0],'Contact request');
assert.equal(eventCopy({kind:'market',listing_status:'approved'},t,'en')[0],'Listing approved');
assert.match(screen,/onPress:\(\)=>erase\(null,through\)/);
assert.match(read('FamilyCalendar.jsx'),/eq\('id',row.id\)\.eq\('user_id',userId\)/);
assert.match(read('FamilyOutingScreen.jsx'),/candidate_ids:candidates.map\(p=>p.id\)/);
console.log('Family life locale: dates, stable calendar data, notification amounts, consent and outing limits checked');
