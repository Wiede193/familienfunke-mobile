import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const load=path=>import('data:text/javascript;base64,'+Buffer.from(read(path)).toString('base64'));
const {answerFamilyQuestion}=await load('FamilyKnowledgeAnswer.js');
const {FAMILY_TOPIC_ARTICLES}=await load('FamilyTopicsKnowledge.js');
const {INCLUSION_ARTICLES}=await load('InclusionKnowledge.js');
const {HEALTH_RESOURCES}=await load('FamilyHealthyContent.js');
const {HOME_ROUTES}=await load('HomeNavigation.js');
const catalog={topics:FAMILY_TOPIC_ARTICLES,inclusion:INCLUSION_ARTICLES,health:HEALTH_RESOURCES,routes:HOME_ROUTES};

const sun=answerFamilyQuestion('Wie groß ist die Sonne?',catalog);
assert.match(sun.answer,/1,4 Millionen Kilometer/);
assert.equal(sun.sources[0].url,'https://science.nasa.gov/sun/facts/');
const kiz=answerFamilyQuestion('Wie beantrage ich Kinderzuschlag?',catalog);
assert.equal(kiz.pageId,'guide');
assert.ok(kiz.answer.includes('Familienkasse'));
assert.ok(kiz.sources[0].url.startsWith('https://'));
const wohn=answerFamilyQuestion('Was ist Wohngeld?',catalog);
assert.equal(wohn.pageId,'guide');
assert.match(wohn.answer,/Wohngeld/);
const inclusion=answerFamilyQuestion('Wo finde ich Hilfe zur Schulbegleitung?',catalog);
assert.equal(inclusion.pageId,'inclusion');
assert.ok(inclusion.sources.length>=1);
const sport=answerFamilyQuestion('Wo gibt es Kinderturnen?',catalog);
assert.equal(sport.pageId,'healthy');
const play=answerFamilyQuestion('Was können wir bei Regen spielen?',catalog);
assert.equal(play.pageId,'play');
const market=answerFamilyQuestion('Kinderwagen kaufen',catalog);
assert.equal(market.pageId,'market');
const unknown=answerFamilyQuestion('Wie repariere ich den Warp-Antrieb eines Raumschiffs?',catalog);
assert.match(unknown.answer,/keine geprüfte Antwort/);
assert.equal(unknown.sources.length,0);
const noPersonal=answerFamilyQuestion('Was steht in meinen privaten Nachrichten?',catalog);
assert.doesNotMatch(noPersonal.answer,/Deine Nachrichten sind/);
assert.doesNotMatch(read('FamilyKnowledgeAnswer.js'),/fetch\s*\(|supabase|api\.openai\.com/);
const home=read('HomeAssistant.jsx'),outing=read('FamilyOutingScreen.jsx'),app=read('App.jsx');
assert.doesNotMatch(home,/functions\.invoke\('ff-app-assistant'/);
assert.doesNotMatch(outing,/functions\.invoke\('ff-app-assistant'/);
assert.doesNotMatch(app,/functions\.invoke\('ff-market-scan'/);
assert.doesNotMatch(app,/functions\.invoke\('ff-market-review'/);
for(const name of ['ff-app-assistant','ff-market-scan']){
 const fn=read('supabase/functions/'+name+'/index.ts');
 assert.match(fn,/if\(true\)return response\(/,'Paid model calls must be blocked server-side');
}
const review=read('supabase/functions/ff-market-review/index.ts');
assert.match(review,/if\(true\)return Response\.json\(\{checked:0,paused:true/);
assert.match(review,/if\(true\)return Response\.json\(\{status:"review_required"/);
console.log('Offline-Wissensassistent: Fragen, Originalquellen, Grenzen und kostenfreie Aufrufpfade geprüft');
