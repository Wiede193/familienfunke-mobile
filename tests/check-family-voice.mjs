const voice=read('FamilyVoiceSearch.jsx'),home=read('HomeAssistant.jsx'),app=read('App.jsx');
assert.match(voice,/requireOptionalNativeModule\('ExpoSpeechRecognition'\)/);
assert.match(voice,/if\(!speech\)return null/);
assert.match(voice,/requiresOnDeviceRecognition:true/);
assert.match(voice,/recordingOptions:\{persist:false\}/);
assert.match(voice,/requestMicrophonePermissionsAsync/);
assert.match(voice,/c\.accept&&c\.phase==='listening'&&event\.isFinal/);
assert.match(voice,/seq!==c\.session/);
assert.match(voice,/speech\.abort\(\)/);
assert.doesNotMatch(voice,/supabase|fetch\(|XMLHttpRequest/);
assert.match(home,/onText=\{updateQuestion\}/);
assert.match(home,/pending\.current\|\|voiceBusy/);
assert.match(app,/from '\.\/FamilyContactsScreen'/);
assert.match(app,/from '\.\/FamilyUI'/);
assert.match(app,/from '\.\/FamilyAppStyles'/);
assert.match(app,/eq\('status','pending'\)/);
assert.match(app,/confirmLabel:status==='declined'/);
console.log('Optional voice integration, explicit actions and module wiring: source contracts checked');
