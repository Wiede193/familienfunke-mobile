import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const app=readFileSync(new URL('../App.jsx',import.meta.url),'utf8');
const extract=(start,end)=>{
  const i=app.indexOf(start),j=app.indexOf(end,i);
  assert.ok(i>=0&&j>i,'Missing '+start);
  return app.slice(i,j);
};
const initial=extract('const load=useCallback(async(silent=false)=>','async function loadMoreFamilies()');
assert.ok((initial.match(/retryRead\(/g)||[]).length>=9,'Only account-scoped reads receive bounded retry');
assert.ok(initial.includes('setConnectionIssue(isTransientFailure(e))'),'Connection indicator must reflect actual failed read');
assert.ok(initial.includes('setConnectionIssue(false)'),'Successful reload must clear connection warning');
assert.ok(app.includes('const [connectionIssue,setConnectionIssue]=useState(false)'));
assert.ok(app.includes('Daten erneut laden'),'Users need a manual reload');
const market=extract('function MarketScreen(','function MarketSortSelect(');
assert.ok(market.includes('Basarsuche erneut versuchen'),'Failed catalog query requires manual retry');
assert.match(market,/\},\[[^\]\n]*\bsearchRetry\b[^\]\n]*\]\);/,'Retry must affect search useEffect');
assert.ok(market.includes("retryRead("),'Buyer search should retry temporary network errors once');
const login=extract('function Login(','export default function App()');
assert.ok(login.includes('signInLock.current=true'),'Login must synchronously lock double taps');
assert.ok(login.includes('finally{signInLock.current=false;setBusy(false);'));
const actions=extract('async function sendChatMessage(body,contactId)','function report(type,id)');
assert.equal((actions.match(/actionGate.current.acquire\(\)/g)||[]).length,3,'All write entrypoints use the same immediate gate');
assert.equal((actions.match(/actionGate.current.release\(ticket\)/g)||[]).length,3,'Write gate must be released in all finally blocks');
assert.ok(actions.includes('if(isTransientFailure(sendError))'),'Ambiguous chat send should not invite blind resending');
assert.ok(!actions.includes('retryRead('),'Writes must NEVER be retried automatically');
assert.ok(app.includes('actionGate.current.reset()'),'Account changes must invalidate old write ticket');
assert.ok(app.includes('const mutationError = error => isTransientFailure(error)'));
const module=readFileSync(new URL('../NetworkResilience.js',import.meta.url),'utf8');
assert.ok(module.includes('return await operation();'),'One bounded retry is permitted');
assert.ok(!module.includes('while ('),'No unbounded retry loops');
console.log('Connection banner, search retry and single-flight actions wired into app.');
