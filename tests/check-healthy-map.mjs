import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const catalog=await import('data:text/javascript;base64,'+Buffer.from(read('FamilyHealthyContent.js')).toString('base64'));
assert.ok(catalog.HEALTH_RESOURCES.length>=10,'Sports and health sources must be substantial');
assert.equal(new Set(catalog.HEALTH_RESOURCES.map(x=>x.id)).size,catalog.HEALTH_RESOURCES.length,'Source IDs unique');
assert.ok(catalog.HEALTH_RESOURCES.every(x=>x.source&&x.title&&x.description&&x.url.startsWith('https://')),'Each source must be traceable');
assert.ok(catalog.findHealthyResources('Sportverein').some(x=>x.id==='lsb'));
assert.ok(catalog.findHealthyResources('Ernährung').some(x=>x.id==='in-form'));
assert.ok(catalog.findHealthyResources('Schwimmen').some(x=>x.id==='lsb'));
assert.ok(catalog.findHealthyResources('Wanderweg').some(x=>x.id==='touren'));
const screen=read('HealthyScreen.jsx');
assert.match(screen,/HEALTH_CATEGORIES\.map/,'Topic chips present');
assert.match(screen,/onPress=\{onOpenMap\}/,'Real link to map rather than static promise');
assert.match(screen,/Linking\.openURL/,'Original source pages must be linked');
assert.match(screen,/Barrierefreiheit/,'Physical accessibility caveat kept');
const app=read('App.jsx'),home=read('HomeAssistant.jsx'),map=read('FamilyMap.jsx');
assert.match(app,/tab==='healthy'\?<HealthyScreen/,'Screen must be reachable');
assert.match(app,/\['guide','Wissen','book'\]/,'Navigation must keep knowledge in five primary tabs');
assert.match(read('FamilyGuide.jsx'),/onPress=\{onOpenHealthy\}/,'Knowledge area must link directly to Healthy');
assert.match(app,/setMapIntent\(\{layer:'bike',returnTab:'healthy'\}\)/,'Map button opens selected cycling layer');
assert.match(app,/\['calendar','home','healthy','inclusion'\]\.includes\(origin\)/,'Navigation back to health and inclusion must work');
assert.match(map,/setPathLayer:function\(kind\)/,'Map layer toggle must be implemented, not decorative');
assert.match(map,/addPathLayer\("ff-bike-paths"/,'Cycling layer must use vector road data');
assert.match(map,/addPathLayer\("ff-walk-paths"/,'Footway overlay must use vector road data');
assert.match(map,/source:"openmaptiles"/,'Paths must use the existing map source');
assert.match(map,/source-layer":"transportation"/,'Path rendering is based on OSM transport metadata');
assert.match(map,/No vector transport source/,'Missing tile metadata must be handled');
assert.match(map,/Keine geprüften Touren/,'Paths are not represented as verified hiking trails');
assert.match(home,/findHealthyResources\(needle/,'Home searches sources directly');
assert.match(home,/findFamilyTopics\(needle/,'Family knowledge must be indexed');
assert.match(home,/findInclusionArticles\(needle/,'Inclusion guidance must be indexed');
assert.match(home,/ff_official_family_events/,'Public official events must be included');
const server=read('supabase/functions/ff-app-assistant/index.ts');
assert.match(server,/"healthy","decisions"\] as const/,'AI allowed route includes health');
console.log('Healthy sources, navigation, universal search and optional map layers passed structural checks.');
