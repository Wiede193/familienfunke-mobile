import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const sql=read('database/ff_market_price_alerts.sql'),app=read('App.jsx'),ui=read('PriceAlertPreference.jsx'),inbox=read('NotificationCenterScreen.jsx');
assert.match(sql,/if new\.moderation_status<>'approved' then return new/);
assert.match(sql,/new\.trade_type='sell' and previous is not null and new\.price_cents<previous/);
assert.match(sql,/f\.created_at<=ev\.created_at/);
assert.match(sql,/coalesce\(p\.enabled,true\)/);
assert.match(sql,/p\.active_since<=ev\.created_at/);
assert.match(sql,/l\.price_cents=ev\.new_price/);
assert.match(sql,/private\.not_blocked\(f\.user_id,l\.seller_id\)/);
assert.match(sql,/f\.user_id<>l\.seller_id/);
assert.match(sql,/excluded\.lowest_notified<private\.ff_market_price_watermark\.lowest_notified/);
assert.match(sql,/foreign key\(user_id,listing_id\) references public\.ff_market_favorites\(user_id,listing_id\) on delete cascade/);
assert.match(sql,/values\(recipient,'price',ev\.listing_id,'approved',ev\.old_price,ev\.new_price\)/);
assert.match(sql,/when\(new\.kind not in \('market','search','price'\)\)/);
assert.match(sql,/limit 100/);
assert.match(sql,/old_price_cents,new_price_cents/);
assert.match(sql,/private\.ff_market_price_preferences enable row level security/);
assert.match(app,/row\.kind==='search'\|\|row\.kind==='price'/);
assert.match(app,/onlyFavorites&&!open&&!boxOpen\?<PriceAlertPreference/);
assert.match(read('PushSettings.jsx'),/<PriceAlertPreference/);
assert.match(ui,/ff_market_price_alert_status/);
assert.match(ui,/ff_market_price_alert_set/);
assert.match(ui,/accessibilityLabel="Preisalarme für gemerkte Artikel"/);
assert.match(inbox,/price:\['Preis gesenkt'/);
assert.match(inbox,/money\(row\.old_price_cents\)/);
assert.match(inbox,/money\(row\.new_price_cents\)/);
assert.match(inbox,/Öffne das Angebot für den aktuellen Preis/);
console.log('Preisalarme: freigegebene Preisänderungen, Merkliste, Stummschaltung, private Benachrichtigung und UI geprüft.');
