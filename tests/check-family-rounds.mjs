import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const {newFamilyRoundDraft,publicMeetingShareText}=await import('data:text/javascript;base64,'+Buffer.from(read('FamilyRoundModel.js')).toString('base64'));
const draft=newFamilyRoundDraft('Frankfurt (Oder)');
assert.equal(draft.max_participants,'8');assert.equal(draft.visibility,'community');
assert.match(draft.description,/öffentlichen Ort/);assert.equal(draft.region_label,'Frankfurt (Oder)');
const row={id:'event-123',moderation_status:'approved',visibility:'community',title:'Private street 99',region_label:'Secret location',description:'An exact home address',organizer_id:'personal',starts_at:'2026-12-08T13:00:00Z',ends_at:'2026-12-08T15:00:00Z'};
const opts={now:Date.parse('2026-12-01T12:00:00Z'),locale:'de-DE',language:'de'};
const text=publicMeetingShareText(row,opts);
assert.match(text,/Familienfunke/);assert.match(text,/kein direkter Einladungslink/);
for(const privateInfo of ['Private street 99','Secret location','An exact home address','personal','event-123'])assert.ok(!text.includes(privateInfo));
assert.equal(publicMeetingShareText({...row,visibility:'contacts'},opts),null);
assert.equal(publicMeetingShareText({...row,moderation_status:'pending'},opts),null);
assert.equal(publicMeetingShareText(row,{...opts,now:Date.parse('2026-12-10T12:00:00Z')}),null);
assert.match(publicMeetingShareText(row,{...opts,language:'en',locale:'en-GB'}),/This is not a direct invitation link/);
const ui=read('App.jsx');
assert.match(ui,/newFamilyRoundDraft\(myRegion\)/);
assert.match(ui,/publicMeetingShareText\(e,/);
assert.match(ui,/Share\.share\(\{message\}\)/);
assert.match(ui,/e\.moderation_status==='approved'&&e\.visibility==='community'/);
assert.match(ui,/await moderateTextOrThrow\(\[event\.title,event\.description,event\.region_label\]\)/);
assert.match(ui,/supabase\.from\('events'\)\.insert\(\{organizer_id:me,\.\.\.event\}\)/);
console.log('Family round: secure template, moderated event flow and non-identifying approved-event sharing checked');
