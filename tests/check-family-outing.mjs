import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const load=p=>import('data:text/javascript;base64,'+Buffer.from(read(p)).toString('base64'));
const {selectOutings,distanceKm,localOrigins,remoteOrigins,orderOutings,planSteps}=await load('FamilyOutingPlan.js');
const {CURATED_FAMILY_PLACES}=await load('FamilyMapCurated.js');
const {NATIONAL_FAMILY_PLACES}=await load('FamilyMapNational.js');
const catalog=[...CURATED_FAMILY_PLACES,...NATIONAL_FAMILY_PLACES];
const origin=localOrigins('Frankfurt (Oder)')[0];
assert.equal(origin.title,'Frankfurt (Oder)');
assert.equal(distanceKm(origin,origin),0);
const prefs={radius:25,budget:50,interest:'any',ages:['preschool','school'],duration:'weekend'};
const candidates=selectOutings(origin,catalog,prefs);
assert.ok(candidates.length>=2);
assert.ok(candidates.every(p=>p.km<=25&&catalog.some(x=>x.id===p.id)));
assert.ok(candidates.some(p=>p.id==='curated-wildpark-frankfurt'));
assert.ok(candidates.every(p=>p.id!=='national-europa-park'));
assert.deepEqual(selectOutings(null,catalog,prefs),[]);
const freeLeads=selectOutings(origin,catalog,{...prefs,budget:0});
assert.ok(freeLeads.length>=1&&freeLeads.every(p=>p.lowCostLead));
assert.ok(selectOutings(origin,catalog,{...prefs,interest:'animals'}).every(p=>p.tags.includes('animals')));
assert.deepEqual(orderOutings(candidates,['fabricated-place',candidates[0].id,candidates[0].id]).map(p=>p.id),[candidates[0].id]);
assert.match(planSteps('weekend',candidates,prefs.ages)[0],/Samstag:/);
assert.ok(planSteps('weekend',candidates,prefs.ages)[0].includes(candidates[0].title));
assert.ok(planSteps('weekend',candidates,prefs.ages)[1].includes(candidates[1].title));
assert.equal(remoteOrigins([{source:'geocode',kind:'Adresse',title:'Musterstraße 1',latitude:52.3,longitude:14.5}]).length,0);
assert.equal(remoteOrigins([{source:'geocode',kind:'Ort',title:'Beispielstadt',latitude:52.3,longitude:14.5}]).length,1);
assert.equal(remoteOrigins([{source:'geocode',kind:'Ort',title:'Außerhalb',latitude:0,longitude:0}]).length,0);
for(const name of ['FamilyMapCurated.js','FamilyMapNational.js']){
 assert.equal(read(name),read('supabase/functions/ff-app-assistant/'+name),'AI catalog must exactly match map catalog');
}
const server=read('supabase/functions/ff-app-assistant/index.ts');
assert.match(server,/ff_app_assistant_claim/);
assert.match(server,/OUTINGS\.has\(id\)/);
assert.match(server,/outing\.ids\.includes\(id\)/);
assert.match(server,/preferences:outing\.preferences,candidates:outing\.candidates/);
assert.match(server,/store:false/);
const ui=read('FamilyOutingScreen.jsx');
assert.match(ui,/candidate_ids:candidates\.map\(p=>p\.id\)/);
assert.match(ui,/orderOutings\(candidates,data\?\.outing_ids\)/);
assert.match(ui,/generate\(false\)/);
assert.match(ui,/Kein Ziel ist als budgetkonform bestätigt/);
assert.match(ui,/Keine Live-Prüfung von Wetter, Öffnungszeiten, Fahrzeiten oder Preisen/);
assert.match(ui,/onMap\(p\.id\)/);
assert.match(ui,/accessibilityState=\{\{selected:active\}\}/);
const app=read('App.jsx');
assert.match(app,/tab==='outing'\?<FamilyOutingScreen/);
assert.match(app,/outingDraft\?\.owner===me/);
assert.match(app,/entryPlaceId=\{mapIntent\?\.id\}/);
assert.match(app,/setMapIntent\(null\);setTab\('outing'\)/);
assert.match(read('FamilyLayoutModel.js'),/DEFAULT_HOME=.*'outing'/);
assert.match(read('FamilyMap.jsx'),/find\(p=>p\.id===entryPlaceId\)/);
console.log('Ausflugsplaner: echte Ziele, Radius, Budgetgrenzen, Altersgruppen, optionaler KI-Vertrag und Kartenübergabe geprüft.');
